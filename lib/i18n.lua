function i18n.windows_language(api)
    if api.GetOS():match("^Win") then
        local command = 'powershell.exe -NoProfile -NonInteractive -WindowStyle Hidden -Command "[System.Globalization.CultureInfo]::CurrentUICulture.Name"'
        local ok, result = pcall(api.ExecProcess, command, 1500)
        local culture = ok and type(result) == "string" and result:match("^0[\r\n]+([%a][%w%-_]*)")
        if culture and (culture:lower() == "zh" or culture:lower():match("^zh[-_]")) then return "zh" end
    end
    return "en"
end

function i18n.app_language(api)
    local config = io.open(api.GetResourcePath() .. "/Scripts/PsyReaSFX/config.tsv", "rb")
    if config then
        for line in config:lines() do
            local language = line:match("^setting\tlanguage\t([%a]+)\r?$")
            if language == "en" or language == "zh" then
                config:close()
                return language
            end
        end
        config:close()
    end
    return i18n.windows_language(api)
end

function i18n.translator(language)
    return function(text)
        if language == "en" then return english[text] or text end
        return text
    end
end

return i18n
